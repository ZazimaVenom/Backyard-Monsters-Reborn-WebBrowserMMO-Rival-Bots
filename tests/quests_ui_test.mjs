import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const ui=await readFile(new URL('../public/assets/ui.js',import.meta.url),'utf8');
const url=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const source=(await readFile(new URL('../public/assets/quests.js',import.meta.url),'utf8')).replace(/from '\.\/ui\.js\?v=[^']+'/,`from '${url(ui)}'`);
const {createQuests,questCard,questRows}=await import(url(source));
let checks=0;
const ok=(c,m)=>{assert.ok(c,m);++checks;};
const reward={id:'BK1',title:'Resources <collected>',group:'Harvests',instruction:'Bank 100 resources.',target:100,progress:100,status:'ready',resources:{twig:50},monsters:{},missing:{}};
const active={...reward,id:'BK2',title:'Resource Collector',target:2000,status:'active'};
const paid={...reward,id:'sample',status:'claimed'};
ok(questRows([paid,active,reward],'Harvests').map(r=>r.status).join(',')==='ready,active,claimed','Claimable items lead first');
ok(questRows([paid,active,reward],'Rewards ready').length===1,'Ready filter excludes paid rewards');
ok(questCard(active,{}).includes('value="100"')&&questCard(active,{}).includes('2,000'),'Native progress is labelled');
ok(!questCard(reward,{}).includes('Resources <collected>') && questCard(reward,{}).includes('data-quest-claim="BK1"'),'Text escaped and expected claim ID');
ok(questCard({...reward,missing:{housing:4}},{}).includes('4 housing space')&&questCard({...reward,missing:{housing:4}},{}).includes('disabled'),'Shows exactly how much housing is missing');
ok(questCard(reward,{},{battle:true}).includes('Finish the invasion'),'Real battle disables award');
ok(!questCard(paid,{}).includes('data-quest-claim'),'No repeat button for paid awards');
const catalog={monsters:{pokey:{name:'Pokey'}}};
ok(questCard({...reward,resources:{},monsters:{pokey:2}},catalog).includes('2 × Pokey'),'Creature rewards show species and quantity');
const state={base:{quests:{entries:[reward,active,paid],counts:{ready:1,claimed:1,earned:0,completed:2}}},user:{id:4},catalog,modal:null,modalEpoch:0,battle:null,activeBattle:null};
const badge={hidden:false,textContent:'',setAttribute(){}}, root={innerHTML:'',contains(){return false;}};
globalThis.document={querySelector(selector){return selector==='#quest-ready-count'?badge:root;}};
const clicks=[],sounds=[],messages=[];let callback;
const quests=createQuests({state,showModal(html,modal){root.innerHTML=html;state.modal=modal;state.modalEpoch++;},
  action(name,input){clicks.push([name,input]);return new Promise(r=>{callback=r;});},toast(msg){messages.push(msg);},audio:{effect(n){sounds.push(n);}}});
const el=(key,value='')=>({dataset:{[key]:value}});
quests.refresh();ok(badge.textContent==='1'&&!badge.hidden,'Ready count visible');
ok(await quests.handleClick(el('questOpen'))&&root.innerHTML.includes('quest-keeper.webp'),'Journal opens with the quartermaster');
await quests.handleClick(el('questTab','Rewards ready'));ok(root.innerHTML.includes('Collect reward for Resources')&&!root.innerHTML.includes('Resource Collector'),'Reward tab scope');
let work=quests.handleClick(el('questClaim','BK1'));
await quests.handleClick(el('questClaim','BK1'));ok(clicks.length===1,'Double click starts one action');
callback({questClaim:{alreadyClaimed:false}});await work;
ok(sounds.join()==='quest'&&messages.at(-1).includes('Reward collected'),'Success acknowledges the actual receipt');
work=quests.handleClick(el('questClaim','BK1'));state.modal=null;state.modalEpoch++;
callback({questClaim:{alreadyClaimed:false}});await work;
ok(sounds.length===1,'Delayed response after close produces no feedback');
await quests.handleClick(el('questOpen'));state.activeBattle={id:1};await quests.handleClick(el('questClaim','BK1'));
ok(clicks.length===2,'An invasion prevents a stale claim');
state.user=null;state.base=null;state.modal=null;quests.refresh();
ok(badge.hidden&&badge.textContent==='0','Logout clears private ready count');
console.log(`Quest UI: ${checks} checks passed.`);
